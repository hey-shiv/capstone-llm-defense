def gen_attacks(bb: Backbone, n: int, seed: int, fams=None) -> list[str]:
    rng = random.Random(seed)
    hints = []
    # SFT trains only on the ID families; the OOD families are held out for BOTH arms.
    SFT_CATEGORIES = fams or ID_ATTACK_FAMILIES

    for _ in range(n):
        cat = rng.choice(SFT_CATEGORIES)
        hints.append((rng.choice(TRAIN_HINTS[cat]), cat))
    prompts = [bb.chat_prompt(attacker_messages(h, c, [])) for h, c in hints]
    with bb.base_policy():
        outs = bb.generate_batch(prompts, max_new_tokens=48, temperature=1.0, top_p=0.95)
    keep = []
    for o in outs:
        t = o.text.strip().strip('"')
        if 3 <= len(t.split()) <= 60 and not is_degenerate(t) and not leaked(t):
            keep.append(t)
    return keep


def build(use_llm: bool = True, target: int = 96, aug: bool = False, out: str = "sft_pairs.jsonl", big: bool = False) -> None:
    rng = random.Random(SEED)
    attacks = list(ID_SEED_ATTACKS)
    bb = Backbone(MODEL_ID)
    if use_llm:
        attacks += gen_attacks(bb, n=160, seed=SEED, fams=list(CATEGORIES) if aug else None)
    seen, uniq = set(), []
    for a in attacks:
        k = " ".join(a.lower().split())
        if k not in seen:
            seen.add(k)
            uniq.append(a)
    print(f"[datagen] {len(uniq)} unique attacks")

    n_benign = int(target * 0.3)
    rows = []
    for i in range(target - n_benign):
        a = uniq[i % len(uniq)]
        rows.append({"prompt": bb.chat_prompt(defender_messages([], a)),
                     "response": rng.choice(REFUSALS), "benign": False, "category": "attack"})
    pool = list(BENIGN_QA)
    if big:
        from attacks2 import train_hard_benign_clean
        HB = train_hard_benign_clean()
    else:
        HB = HARD_BENIGN_TRAIN
    if aug:   # self-distilled answers (frozen base model, greedy) for the attack-looking benign prompts
        with bb.base_policy():
            outs = bb.generate_batch([bb.chat_prompt(defender_messages([], q)) for q in HB],
                                     max_new_tokens=64, do_sample=False)
        pool += [(q, o.text) for q, o in zip(HB, outs)
                 if not leaked(o.text) and not is_degenerate(o.text) and not is_refusal_dominant(o.text)]
        print(f"[datagen] {len(pool) - len(BENIGN_QA)} hard-benign pairs kept")
    for i in range(n_benign):
        q, ans = pool[i % len(pool)]
        rows.append({"prompt": bb.chat_prompt(defender_messages([], q)),
                     "response": ans, "benign": True, "category": "benign"})
    rng.shuffle(rows)
    DATA.mkdir(exist_ok=True)
    with open(DATA / out, "w") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")
    print(f"[datagen] wrote {len(rows)} pairs -> {DATA / out}")


